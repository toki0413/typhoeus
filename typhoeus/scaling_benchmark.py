"""p53 标度指数的对标：模型间对比不可行，改为理论一致性检验。

原定第 5 件是"与已发表模型（LISFLOOD-FP / WRF-Hydro）同域同事件对比"。
**做不到**，原因如实记在产物里。本件改为两件能做的事：

  1 **文献对标可行性判定**：记录检索到的候选文献类别、为什么不能直接对标
  2 **理论一致性检验**：把实测指数与模型方程给出的理论界对比。
     这一条是严格的，且能把数字接到物理机制上。

理论依据
--------
本模型里 85.4% 的雨量从管网排出（p45 实测），仅 1.9% 下渗、6.4% 留在地表。
在这样一个"排水主导"的系统里：

  · 若完全没有排水（纯蓄满），峰值水深应与雨量同阶 → b ≈ 1
  · 排水越强，水深对雨量的敏感性越低 → b → 0
  · 故 **0 < b_depth < 1** 是排水主导区间的理论界

实测 b_depth = 0.434 落在该区间内，且处于"强排水"一侧，
与 85.4% 的排水占比一致。

用法：python -m typhoeus.scaling_benchmark
"""

from __future__ import annotations

import json
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"


def _load(n: str) -> dict:
    p = OUT / n
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def main() -> int:
    vs = _load("p50_验证与统计.json")
    pw = _load("p45_碳水耦合.json")

    b_depth = ((vs.get("6_深度标度_b") or {}).get("b_点估计"))
    b_depth_ci = ((vs.get("6_深度标度_b") or {}).get("b_95CI"))
    b_q = ((vs.get("5_bootstrap_Q标度") or {}).get("b_点估计"))
    b_q_ci = ((vs.get("5_bootstrap_Q标度") or {}).get("b_95CI"))
    b_q_range = ((vs.get("2_零值处理敏感性") or {}).get("b_取值范围"))

    share = (pw.get("A_占比_pct") or {})
    drain_share = share.get("排水")

    # 理论一致性
    in_bounds = (b_depth is not None and 0.0 < b_depth < 1.0)
    # 排水占比越高，b 应越低。用 85.4% 作参照给一个"强排水"判据
    strong_drain = (drain_share is not None and drain_share >= 0.80)

    payload = {
        "名称": "标度指数对标：模型间对比不可行，改做理论一致性检验",
        "生成时间": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "原定任务与判定": {
            "原定": "与已发表模型（LISFLOOD-FP / WRF-Hydro）同域同事件对比",
            "判定": "**不可行**",
            "原因": [
                "两个模型都需完整管网拓扑与断面数据；本项目恰恰缺管网台账"
                "（这正是顶托参数只能取文献量级的原因）。",
                "LISFLOOD-FP 需 2D 水动力求解与稳定步长调参；WRF-Hydro 需 "
                "WRF 气象场驱动。任一者的环境搭建与标定都是多日工作。",
                "即便跑通，输出口径（水深场/流量）与本项目的『功能损失 Q』"
                "不同源，仍需额外的损失映射函数才能比较。",
            ],
            "结论": "**这一件没有完成。** 不得在任何材料中暗示做过模型间对比。",
        },
        "文献对标的可行性": {
            "检索到的候选类别": [
                "保险损失 vs 强降雨（Bouwer 等 2019，瑞典两城，JFRM）"
                "——与我们的 Q vs 雨量最接近，但损失是货币口径",
                "分布式时变增益水文水动力耦合模型的幂律拟合"
                "——多为『水深 vs 影响因素』的回归式，非跨事件标度指数",
                "洪泛平原水深—汇水面积幂律（h ∝ A^b）"
                "——几何关系，与降雨标度不同物理量",
            ],
            "为什么不能直接对标": [
                "物理量不同：我们测的是『域内功能损失 Q vs 面雨量』，"
                "文献多为『货币损失 vs 降雨』或『水深 vs 汇水面积』。",
                "尺度不同：16.5×8.9 km、144×270 网格的城区，"
                "与文献的流域/国家尺度不可比。",
                "标定目标不同：我们的 Q 由模型自身生成，文献损失是真实现金赔损。",
            ],
            "结论": ("**没有找到可直接对标同一物理量的已发表指数。** "
                     "这不是检索不足，而是『城市功能损失 vs 面雨量』这一量纲组合"
                     "本身在文献中罕见——这既是本项目的空白填补点，"
                     "也意味着**无法用文献值验证我们的 1.64**。"),
        },
        "实测指数": {
            "深度标度_b": b_depth, "深度_b_95CI": b_depth_ci,
            "深度_b_样本量": (vs.get("6_深度标度_b") or {}).get("n"),
            "Q标度_b": b_q, "Q_b_95CI": b_q_ci,
            "Q_b_零值处理下的取值范围": b_q_range,
            "排水占比_pct": drain_share,
        },
        "理论一致性检验": {
            "理论界": "在排水主导的城区，0 < b_depth < 1："
                   "b=1 对应纯蓄满（无排水），b→0 对应排水完全控制。",
            "判据": "b_depth 落在 (0,1) 且排水占比 ≥80%",
            "实测": f"b_depth={b_depth}，排水占比 {drain_share}%",
            "通过": bool(in_bounds and strong_drain),
            "意义": ("实测 b 落在理论界内且处于强排水一侧，"
                     "与『85.4% 雨量从管网排出』这一独立测量**互相印证**。"
                     "这是本件唯一严格成立的检验。"),
        },
        "结论": [],
        "边界": [
            "本件**没有完成**原定的模型间对比，不得据此声称『已与 LISFLOOD-FP 对齐』。",
            "理论界 (0,1) 是**定性界**，不是精确预测；它只能排除 b≥1 或 b≤0，"
            "不能验证 0.434 这个具体值。",
            "排水占比 85.4% 来自 p45 的水量账，与 b 来自不同产物，"
            "两者相互印证但非独立验证。",
            "文献检索在 2 次查询内未取得可核对的原值（部分来源需人机验证），"
            "故『无同类指数』应记为**未穷尽**而非**已证否**。",
        ],
    }

    payload["结论"] = [
        ("**第 5 件未完成。** 模型间对比需要管网拓扑与多日环境搭建，"
         "本项目缺的正是管网台账。任何材料都不得暗示做过对比。"),
        ("**文献对标也没做成**：『城市功能损失 vs 面雨量』这一量纲组合"
         "在检索到的文献中没有可直接比较的指数。这既说明我们的口径少见，"
         "也说明**无法用文献值验证 1.64**。"),
        ("**唯一严格成立的是理论一致性检验**："
         f"b_depth={b_depth} 落在排水主导区间的理论界 (0,1) 内，"
         f"且与『排水占 {drain_share}%』这一独立测量方向一致——"
         "排水越强，水深对雨量越不敏感。"),
        ("**所以第 5 件的正确表述是**："
         "『未能对标，但给出了内部的物理一致性检验』，"
         "而不是『已对标』或『无可对标』。"),
    ]

    (OUT / "p53_标度指数对标.json").write_text(
        json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"  b_depth={b_depth} CI {b_depth_ci}  排水占比 {drain_share}%")
    print(f"  理论一致性: {'通过' if payload['理论一致性检验']['通过'] else '不通过'}"
          f"（界 (0,1)，判据含排水≥80%）")
    print(f"  模型间对比: 未完成（已如实记录）")
    print(f"→ {OUT / 'p53_标度指数对标.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
