def write_monitor_sites(lon_min, lon_max, lat_min, lat_max, n=149, seed=20210725):
    """按公开的布设逻辑在计算域内生成占位坐标。

    这不是真实点位。只用于让下游链路有可迭代的数组形状，
    真实坐标到位后整体替换即可，接口不变。
    """
    import numpy as np

    rng = np.random.default_rng(seed)
    sites = []
    # 按行政区大致占比分配：海曙与鄞州是主城区，点位最密
    dist = {"海曙": 0.26, "鄞州": 0.30, "江北": 0.16, "镇海": 0.13, "奉化": 0.11, "大榭": 0.04}
    pid = 1
    for dist_name, frac in dist.items():
        k = max(1, int(round(n * frac)))
        lons = rng.uniform(lon_min, lon_max, k)
        lats = rng.uniform(lat_min, lat_max, k)
        for lo, la in zip(lons, lats):
            # 合成一条退水曲线：起涨时间错开，峰值与退水速率随机
            t0 = float(rng.uniform(0, 14))          # 起涨时刻 h
            tpk = t0 + float(rng.uniform(4, 11))    # 峰值时刻 h
            dpk = float(rng.uniform(0.12, 0.72))    # 峰值水深 m
            kd = float(rng.uniform(0.10, 0.32))     # 退水速率 1/h
            sites.append({
                "site_id": f"MS{pid:03d}",
                "district": dist_name,
                "lon": round(float(lo), 6),
                "lat": round(float(la), 6),
                "t_start_h": round(t0, 2),
                "t_peak_h": round(tpk, 2),
                "peak_depth_m": round(dpk, 3),
                "recession_coef_per_h": round(kd, 3),
                "provenance": "synthetic(布设逻辑占位)",
            })
            pid += 1
    p = OUT / "monitor_sites_synthetic.json"
    p.write_text(json.dumps({
        "说明": "149 个内涝监测点的占位数据，provenance=synthetic，不得当作真实坐标",
        "spec": MONITOR_SITES_SPEC,
        "sites": sites,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return p, len(sites)


