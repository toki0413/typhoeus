# 5. 气象站小时序列（合成，但锚定到实测累计量）
# ============================================================
def write_hourly_series():
    """合成逐小时降雨，使站点累计量对上实测通报值。

    时间核沿用 kernel.rainfall_field 的钟形形式，保证驱动源口径一致。
    输出的不是实测序列，是"与实测累计量一致的驱动假设"。
    """
    import numpy as np

    R_MAX = 11.3
    T_HALF = 2.0
    p = OUT / "rain_hourly_synthetic.json"
    series = []
    for st, lon, lat, acc, valid_at, dur, _src in RAIN_STATIONS:
        # 以累计量反推强度缩放
        scale = acc / 250.0
        t = np.arange(-12, 61, dtype=np.float64)
        tc = 22.0    # 峰值时刻相对基准点的偏移 h
        w = np.exp(-0.5 * ((t - tc) / T_HALF) ** 2)
        r = R_MAX * scale * w
        series.append({
            "station": st, "lon": lon, "lat": lat,
            "target_accum_mm": acc,
            "series_mm_h": {f"{int(tt):+d}": round(float(v), 3)
                            for tt, v in zip(t, r)},
            "provenance": "synthetic(锚定实测站点累计量)",
        })
    p.write_text(json.dumps({
        "说明": "逐小时序列为合成，锚定到实测站点累计量；不得当作实测序列使用",
        "驱动口径": "与 typhoeus.kernel.rainfall_field 同一钟形核，R_MAX=11.3, T_HALF=2.0",
        "series": series,
    }, ensure_ascii=False, indent=2), encoding="utf-8")
    return p


